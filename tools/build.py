#!/usr/bin/env python3
"""Merges tools/words.json + tools/ko/bNN.json into data.js (run after translations are complete)."""
import glob, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
words = json.load(open(f"{HERE}/words.json"))
ko = {}
for f in sorted(glob.glob(f"{HERE}/ko/b*.json")):
    for e in json.load(open(f)):
        ko[e["id"]] = e
missing = [w["id"] for w in words if w["id"] not in ko]
if missing:
    print("missing translations:", len(missing), missing[:10])
topics = json.load(open(f"{HERE}/topics.json"))
tmap = {}
for f in sorted(glob.glob(f"{HERE}/topics/t*.json")):
    tmap.update({int(k): int(v) for k, v in json.load(open(f)).items()})
rows = []
for w in words:
    k = ko.get(w["id"])
    if not k:
        continue
    exs = [[d, k["ex"][i] if i < len(k["ex"]) else ""] for i, d in enumerate(w["ex"])]
    rows.append({"id": w["id"], "de": w["de"], "art": w["art"], "kind": w["kind"], "extra": w["extra"],
                 "note": w["note"], "ko": k["ko"], "ex": exs, "l": w["letter"], "t": tmap.get(w["id"], 22)})
open(f"{HERE}/../data.js", "w", encoding="utf-8").write(
    "// generated by tools/build.py\nconst TOPICS = " + json.dumps(topics, ensure_ascii=False) + ";\nconst WORDS = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(rows), "words written")
